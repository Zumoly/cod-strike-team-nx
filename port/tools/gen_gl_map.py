#!/usr/bin/env python3
"""Stage 3: generate the GLES/EGL binding table from libunity's real import list.

Every imported name gets exactly one row, a subsystem, and its deko3D target.
Rows without a real implementation bind to a weak stub that stops with the name,
so a missing function fails loudly instead of misrendering.  Defining shim_<name>
anywhere replaces the stub at link time.

usage: gen_gl_map.py <libunity.imports.txt> <out_c> <out_md>
"""
import pathlib
import re
import sys

# (regex, subsystem, deko3D mapping); first match wins.
RULES = [
    (r"^egl(Swap)", "present", "dkQueueAcquireImage / dkQueuePresentImage on a DkSwapchain"),
    (r"^egl", "context", "fixed single config over nwindowGetDefault(); DkDevice/DkQueue owned by the renderer"),
    (r"^gl(Gen|Delete)(Buffers)$", "buffer", "handle table of DkMemBlock suballocations"),
    (r"^gl(BindBuffer|BufferData|BufferSubData)$", "buffer", "versioned ring in CPU-visible GPU memory, orphaned per update"),
    (r"^gl(VertexAttribPointer|EnableVertexAttribArray|DisableVertexAttribArray|GetVertexAttrib\w*)$", "vertex",
     "DkVtxAttribState + DkVtxBufferState; client pointers copied into the ring at draw"),
    (r"^gl(Draw\w+)$", "draw", "dkCmdBufDraw / dkCmdBufDrawIndexed after flushing dirty state"),
    (r"^gl(Gen|Delete)(Textures)$", "texture", "handle table of DkImage + descriptor slot"),
    (r"^gl(BindTexture|ActiveTexture|TexParameteri)$", "texture", "DkSampler / DkImageDescriptor tables, dkCmdBufBindTextures"),
    (r"^gl(TexImage2D|TexSubImage2D|CompressedTex\w+|CopyTexSubImage2D|GenerateMipmap)$", "texture",
     "dkCmdBufCopyBufferToImage from staging; PVRTC decoded on CPU; mips via dkCmdBufBlitImage"),
    (r"^gl(PixelStorei)$", "texture", "tracked unpack alignment for staging copies"),
    (r"^gl(Gen|Delete)(Framebuffers|Renderbuffers)$", "target", "handle table of attachment sets"),
    (r"^gl(BindFramebuffer|BindRenderbuffer|FramebufferTexture2D|FramebufferRenderbuffer|RenderbufferStorage|CheckFramebufferStatus|GetFramebufferAttachmentParameteriv)$",
     "target", "dkCmdBufBindRenderTargets with DkImageView"),
    (r"^gl(Clear\w*)$", "target", "dkCmdBufClearColor / dkCmdBufClearDepthStencil"),
    (r"^gl(ReadPixels)$", "target", "dkCmdBufCopyImageToBuffer, then fence wait"),
    (r"^gl(CreateShader|DeleteShader|ShaderSource|CompileShader|GetShader\w+)$", "shader",
     "lookup of precompiled DKSH by source hash (tools/translate_shaders.py)"),
    (r"^gl(CreateProgram|DeleteProgram|AttachShader|LinkProgram|GetProgram\w+|BindAttribLocation|GetAttribLocation|GetActive\w+|GetUniformLocation|UseProgram)$",
     "shader", "DkShader pair + reflection from shader_db.json, dkCmdBufBindShaders"),
    (r"^glUniform", "uniform", "writes std140 shadow block; dkCmdBufPushConstants before draw"),
    (r"^gl(Enable|Disable)$", "state", "DkRasterizerState / DkDepthStencilState / DkColorState"),
    (r"^gl(Blend\w+|ColorMask)$", "state", "DkBlendState, DkColorWriteState"),
    (r"^gl(Depth\w+|Stencil\w+)$", "state", "DkDepthStencilState, dkCmdBufSetStencil"),
    (r"^gl(CullFace|FrontFace)$", "state", "DkRasterizerState"),
    (r"^gl(Viewport|Scissor)$", "state", "dkCmdBufSetViewports / dkCmdBufSetScissors, Y flipped for FBOs as needed"),
    (r"^gl(Flush|Finish)$", "sync", "dkQueueFlush / dkQueueWaitIdle"),
    (r"^gl(GetIntegerv|GetString|GetError)$", "query", "static caps table; reports ES 2.0 with a chosen extension list"),
]

names = [n for n in pathlib.Path(sys.argv[1]).read_text().split() if re.match(r"^(gl|egl)[A-Z]", n)]
rows, unmapped = [], []
for n in names:
    for pat, sub, target in RULES:
        if re.match(pat, n):
            rows.append((n, sub, target))
            break
    else:
        unmapped.append(n)
if unmapped:
    sys.exit(f"unmapped imports: {unmapped}")

c = ['// Generated by tools/gen_gl_map.py from libunity.so\'s import table. Do not edit.',
     '#include "port/gl_shim.h"', '#include <stdio.h>', '#include <stdlib.h>', '',
     '// Weak aliases must target a definition in this file.  They all share it, so',
     '// the caller\'s return address is what identifies the missing import.',
     'void gl_unimplemented(void)', '{',
     '    fprintf(stderr, "unimplemented GL import, called from %p\\n", __builtin_return_address(0));',
     '    abort();', '}', '']
for n, _, _ in rows:
    c.append(f'void shim_{n}(void) __attribute__((weak, alias("gl_unimplemented")));')
c += ['', 'const struct gl_import gl_imports[] = {']
c += [f'    {{"{n}", shim_{n}}},' for n, _, _ in rows]
c += ['};', f'const unsigned gl_import_count = {len(rows)};', '']
pathlib.Path(sys.argv[2]).write_text("\n".join(c), encoding="utf-8", newline="\n")

md = ["# GLES/EGL import map", "",
      f"Generated from libunity.so: {len(rows)} imports. Status is tracked by which `shim_*` symbols exist.", "",
      "| Import | Subsystem | deko3D mapping |", "|---|---|---|"]
md += [f"| `{n}` | {s} | {t} |" for n, s, t in rows]
pathlib.Path(sys.argv[3]).write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
print("mapped", len(rows), "imports")
